const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE, headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1355, height: 892 } });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    const date = days => new Date(Date.now() - days * 86400000).toISOString();
    const apps = [1, 2].map(id => ({ key: `ios:us:${id}`, title: id === 1 ? 'Backup App' : 'Translate App', appUrl: `https://apps.apple.com/us/app/id${id}`, platform: 'ios', developer: 'Fixture studio', reason: 'Related app to investigate' }));
    let failure = false, delay = false, collectionCount = 0;
    const reports = [];
    await page.route('**/api/market/classifier', route => route.fulfill({ json: { configured: true, provider: 'gemini', model: 'fixture', version: 'market-semantic-v1' } }));
    await page.route('**/api/market/search-apps', route => route.fulfill({ json: { apps: [apps[(route.request().postDataJSON().page || 1) - 1]], totalPages: 2, total: 2, limit: 100 } }));
    await page.route('**/api/market/resolve-app', route => route.fulfill({ json: apps.find(app => app.appUrl === route.request().postDataJSON().url) }));
    await page.route('**/api/market/discover', route => route.fulfill({ json: { apps: [apps[1]], country: 'us', scope: 'Related apps' } }));
    await page.route('**/app-store/process-url', async route => {
      collectionCount++;
      if (delay) await new Promise(resolve => setTimeout(resolve, 1800));
      const app = apps.find(app => app.appUrl === route.request().postDataJSON().url);
      const text = app === apps[0] ? 'Backup stops before it finishes.' : 'Translation misses the meaning.';
      await route.fulfill({ json: { details: { title: app.title }, reviews: { source: 'review-feed', country: 'us', reviews: [{ id: 'new', text, date: date(10), score: 2 }, { id: 'old', text: `${text} This happened before.`, date: date(60), score: 1 }] } } });
    });
    await page.route('**/api/market/classify', route => route.fulfill({ json: { version: 'market-semantic-v1', model: 'fixture', provider: 'gemini', analyzedAt: date(0), classifications: route.request().postDataJSON().reviews.map(review => ({ key: review.key, labels: [{ topic: { id: 'topic-0000000000000001', name: 'Core task reliability', description: 'Completing the task' }, intent: 'complaint', polarity: 'negative', issue: 'Task interrupted', evidence: review.text }] })) } }));
    await page.route('**/api/market/opportunities', route => {
      const body = route.request().postDataJSON(); reports.push(body);
      return route.fulfill(failure ? { status: 503, json: { error: 'Fixture analysis failed' } } : { json: { version: 'market-opportunities-v1', provider: 'gemini', model: 'fixture', generatedAt: date(0), opportunities: [{ id: 'opportunity-0000000000000001', title: `${body.product}: ${body.days}-day opportunity`, scenario: 'A user tries to complete the core task', obstacle: 'Task interrupted', consequence: 'Cannot complete the task', hypothesis: 'Test reliable completion', nextWho: 'An affected user', nextQuestion: 'What happened?', nextExperiment: 'Observe task completion', unknowns: ['Demand unverified'], evidenceKeys: body.evidence.map(item => item.key) }] } });
    });
    await page.goto(`${process.env.QA_BASE_URL || 'http://127.0.0.1:5173'}/market`, { waitUntil: 'domcontentloaded', timeout: 60000 });
    const nav = page.getByRole('navigation', { name: 'Product research' });
    const screenshot = name => page.screenshot({ path: path.join(process.env.QA_OUTPUT_DIR || require('node:os').tmpdir(), name), fullPage: true });
    const overview = () => nav.getByRole('button', { name: 'Overview', exact: true }).click();
    const analyze = () => page.getByRole('button', { name: 'Analyze an app', exact: true }).first().click();
    assert.equal(await page.getByText('Saved explorations', { exact: true }).count(), 0);
    assert.equal(await page.getByRole('button', { name: 'Describe a situation' }).count(), 0);
    await analyze();
    await page.getByLabel('App name or store link').fill('photo');
    await page.getByRole('button', { name: /Backup App.*Fixture studio/ }).waitFor();
    await page.getByRole('button', { name: 'Next app page' }).click();
    await page.getByRole('button', { name: /Translate App.*Fixture studio/ }).waitFor();
    await page.getByRole('button', { name: 'Previous app page' }).click();
    await page.getByRole('button', { name: /Backup App.*Fixture studio/ }).click();
    await page.getByRole('heading', { name: 'Confirm analysis scope' }).waitFor();
    assert.equal(collectionCount, 0, 'Selecting an app must not collect feedback');
    assert.equal(reports.length, 0, 'Selecting an app must not generate a report');
    await page.getByLabel('Analysis period').selectOption('30');
    await page.getByRole('button', { name: 'Back', exact: true }).click();
    assert.equal(await page.getByLabel('App name or store link').inputValue(), 'photo');
    await page.getByRole('button', { name: /Backup App.*Fixture studio/ }).click();
    assert.equal(await page.getByLabel('Analysis period').inputValue(), '30');
    await page.getByLabel('Analysis period').selectOption('90');
    await page.getByRole('button', { name: 'Generate analysis', exact: true }).click();
    await page.getByRole('heading', { name: 'Backup App: 90-day opportunity', exact: true }).first().waitFor();
    assert.equal(await page.getByRole('dialog').count(), 0);
    assert.equal(await page.getByRole('button', { name: 'Start research', exact: true }).count(), 0);
    assert.equal(reports.length, 1);
    assert.equal(reports[0].evidence.length, 2);
    await page.getByRole('button', { name: 'Explore the opportunity', exact: true }).click();
    await page.getByRole('dialog').getByText('Backup stops before it finishes.', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Save to decision board', exact: true }).click();
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export brief' }).click();
    assert.equal((await download).suggestedFilename(), 'voicely-opportunity.md');
    await page.getByRole('button', { name: 'Close dialog' }).click();
    await nav.getByRole('button', { name: /Decision board/ }).click();
    await page.getByLabel('Findings & notes').fill('Interview scheduled.');
    await page.getByLabel('Decision status for Backup App: 90-day opportunity').selectOption('interview');
    await page.reload({ waitUntil: 'domcontentloaded' });
    await nav.getByRole('button', { name: /Decision board/ }).click();
    assert.equal(await page.getByLabel('Findings & notes').inputValue(), 'Interview scheduled.');
    await overview();
    await page.getByLabel('Time range', { exact: true }).selectOption('30');
    await page.getByRole('heading', { name: 'Backup App: 30-day opportunity', exact: true }).first().waitFor();
    assert.equal(reports.at(-1).evidence.length, 1);
    await screenshot('sites-flow-overview-desktop.png');
    await nav.getByRole('button', { name: 'Review explorer', exact: true }).click();
    await page.getByText('1 matching reviews', { exact: true }).waitFor();
    await page.getByLabel('Search reviews', { exact: true }).fill('missing phrase');
    await page.getByText('0 matching reviews', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Clear filters' }).click();
    await page.getByText('1 matching reviews', { exact: true }).waitFor();
    await nav.getByRole('button', { name: 'Compare apps', exact: true }).click();
    await page.getByRole('button', { name: 'Analyze for comparison', exact: true }).click();
    await page.getByRole('heading', { name: 'Confirm analysis scope' }).waitFor();
    await page.getByRole('button', { name: 'Generate analysis', exact: true }).click();
    await page.getByRole('heading', { name: 'Translate App', exact: true }).first().waitFor();
    assert.match(await page.getByRole('button', { name: 'Change app' }).innerText(), /Backup App/);
    await overview();
    await analyze();
    await page.getByLabel('App name or store link').fill(apps[1].appUrl);
    const beforeCached = collectionCount;
    await page.getByRole('button', { name: 'Analyze store link' }).click();
    await page.getByRole('heading', { name: 'Confirm analysis scope' }).waitFor();
    assert.equal(collectionCount, beforeCached);
    await page.getByRole('button', { name: 'Generate analysis', exact: true }).click();
    await page.getByRole('heading', { name: 'Translate App: 30-day opportunity', exact: true }).first().waitFor();
    assert.equal(collectionCount, beforeCached, 'Selecting a completed app uses its saved result');
    assert.equal(await page.getByRole('heading', { name: 'Backup App: 30-day opportunity', exact: true }).count(), 0);
    await page.getByRole('button', { name: 'Set up monitor' }).click();
    await page.getByText(/Manual monitoring/).waitFor();
    await page.getByRole('button', { name: 'View analysis', exact: true }).click();
    failure = true;
    await page.getByLabel('Time range', { exact: true }).selectOption('90');
    await page.getByRole('alert').filter({ hasText: 'Fixture analysis failed' }).waitFor();
    assert.equal(await page.getByLabel('Time range', { exact: true }).inputValue(), '30');
    await page.getByRole('heading', { name: 'Translate App: 30-day opportunity', exact: true }).first().waitFor();
    failure = false; delay = true;
    await page.getByRole('button', { name: 'Retry analysis', exact: true }).click();
    await page.getByRole('button', { name: 'Stop analysis', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Analysis stopped' }).waitFor();
    assert.equal(await page.getByLabel('Time range', { exact: true }).inputValue(), '30');
    delay = false;
    await page.getByRole('button', { name: 'Retry analysis', exact: true }).click();
    await page.getByRole('heading', { name: 'Translate App: 90-day opportunity', exact: true }).first().waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    await screenshot('sites-flow-overview-mobile.png');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await analyze();
    await screenshot('sites-flow-analyze-mobile.png');
    assert.ok(await page.getByRole('dialog').evaluate(el => el.scrollWidth <= el.clientWidth));
    await page.getByRole('button', { name: /Backup App.*Fixture studio/ }).click();
    await page.getByRole('heading', { name: 'Confirm analysis scope' }).waitFor();
    await screenshot('sites-flow-scope-mobile.png');
    assert.ok(await page.getByRole('dialog').evaluate(el => el.scrollWidth <= el.clientWidth));
    const beforeCancel = collectionCount;
    await page.getByRole('button', { name: 'Close dialog' }).click();
    assert.equal(collectionCount, beforeCancel, 'Closing scope must not start collection');
    await page.getByRole('button', { name: 'Open navigation' }).click();
    await nav.getByRole('button', { name: /Decision board/ }).click();
    await page.getByLabel('Findings & notes').waitFor();
    assert.equal(await page.getByLabel('Findings & notes').inputValue(), 'Interview scheduled.');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.deepEqual(errors, []);
    console.log('PASS: Sites flow, search/pagination/URL, automatic analysis, consistent scope, evidence/save/export, notes persistence, related comparison, isolated apps, errors/cancel/retry, desktop/mobile');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
